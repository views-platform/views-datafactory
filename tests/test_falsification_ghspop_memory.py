class TestF3PeakMemoryEstimate:
    """F3 supplementary: verify that the estimated number of
    non-zero output rows would exceed safe Python list capacity
    on an 8 GB server."""

    @pytest.mark.slow
    def test_list_overhead_estimate(self) -> None:
        """Python list of 60M ints should exceed 2 GB."""
        n = 60_000_000
        int_size = sys.getsizeof(1000)
        ptr_size = 8
        per_entry = int_size + ptr_size

        three_lists_gb = (3 * n * per_entry) / (1024**3)
        assert three_lists_gb > 4.0, (
            f"3 lists of {n} entries = {three_lists_gb:.1f} GiB — "
            f"expected > 4 GiB. If this passes, the memory model "
            f"is correct and lists ARE the bottleneck."
        )
