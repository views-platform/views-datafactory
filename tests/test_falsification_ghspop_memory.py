class TestF3ListAccumulationMemory:
    """F3 (hard): The builder accumulates three Python lists for all
    non-zero cell-months (~60M entries, ~6.5 GB). These are never
    deleted — they coexist with the Arrow table during pa.table()
    creation, pushing peak to 7.4–8.3 GB."""

    def test_lists_deleted_before_digest(self) -> None:
        """pgid_rows, month_id_rows, pop_count_rows must be deleted
        after Arrow table creation to free ~6.5 GB."""
        import ast
        from pathlib import Path

        src = Path(
            "src/datafactory_viewpoint/builders/ghspop_v1.py"
        ).read_text()
        tree = ast.parse(src)

        for node in ast.walk(tree):
            if not isinstance(node, ast.FunctionDef):
                continue
            if node.name != "build_ghspop_v1":
                continue

            del_targets: set[str] = set()
            for child in ast.walk(node):
                if isinstance(child, ast.Delete):
                    for target in child.targets:
                        if isinstance(target, ast.Name):
                            del_targets.add(target.id)

            for name in (
                "pgid_rows", "month_id_rows", "pop_count_rows",
            ):
                assert name in del_targets, (
                    f"{name} is never deleted in build_ghspop_v1 — "
                    f"~60M Python objects (~2 GB) remain in scope "
                    f"during Arrow table creation and digest "
                    f"computation, risking OOM on 8 GB server"
                )


